"""Compose the main prompt from the agent and its plugins.

Five fixed sections, in order (``plugins-and-composition.md``, "Composed main
prompt"):

1. **identity** -- "You are {name}, {role}.", owned by the agent;
2. **guidelines** -- universal behavior, owned by ``core``;
3. **rendering** -- what CLIO can display, generated by ``core`` from the
   catalogs the UI renders from;
4. **capabilities** -- one fragment per plugin that needs one;
5. **domain** -- science, manufacturing and similar framing.

Ordering is deterministic: sections first, then plugin resolution order, then
fragment file order. Stable sections lead, so toggling a plugin only changes the
prompt from the capabilities section down. Templating is minimal: agent identity
and environment variables, nothing else.
"""

from __future__ import annotations

import hashlib
import os
import re
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, field
from typing import Any

from clio_agent.plugins.records import FragmentRecord

SECTIONS = ("identity", "guidelines", "rendering", "capabilities", "domain")
FRAGMENT_TOKEN_BUDGET = 150
_TEMPLATE_RE = re.compile(r"\{\{\s*(agent\.(?:id|name|role)|env\.[A-Za-z_][A-Za-z0-9_]*)\s*\}\}")


@dataclass(frozen=True)
class ComposedFragment:
    id: str
    plugin: str
    section: str
    text: str
    tokens: int
    path: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "plugin": self.plugin,
            "section": self.section,
            "text": self.text,
            "tokens": self.tokens,
            "path": self.path,
        }


@dataclass(frozen=True)
class ComposedPrompt:
    fragments: tuple[ComposedFragment, ...]
    warnings: tuple[str, ...] = field(default_factory=tuple)

    @property
    def text(self) -> str:
        return "\n\n".join(fragment.text for fragment in self.fragments if fragment.text)

    @property
    def digest(self) -> str:
        return hashlib.sha256(self.text.encode("utf-8")).hexdigest()

    def to_dict(self) -> dict[str, Any]:
        return {
            "sections": [
                {
                    "section": section,
                    "fragments": [f.to_dict() for f in self.fragments if f.section == section],
                }
                for section in SECTIONS
            ],
            "text": self.text,
            "digest": self.digest,
            "warnings": list(self.warnings),
        }


def render_template(
    text: str, *, identity: Mapping[str, str], environ: Mapping[str, str] | None = None
) -> str:
    """Substitute ``{{agent.id|name|role}}`` and ``{{env.NAME}}``; nothing else."""

    env = os.environ if environ is None else environ

    def replace(match: re.Match[str]) -> str:
        key = match.group(1)
        if key.startswith("agent."):
            return str(identity.get(key.removeprefix("agent."), ""))
        return str(env.get(key.removeprefix("env."), ""))

    return _TEMPLATE_RE.sub(replace, text)


def fragment_applies(
    fragment: FragmentRecord, tools: Sequence[str], plugins: Sequence[str]
) -> bool:
    """Whether a fragment's ``when`` holds for the resolved tools and plugins.

    A ``when.tools`` entry holds when a resolved tool has exactly that name or
    starts with ``<entry>_`` (an MCP or built-in namespace such as ``shell``).
    """

    tool_set = set(tools)
    for wanted in fragment.when_tools:
        if wanted not in tool_set and not any(name.startswith(f"{wanted}_") for name in tool_set):
            return False
    return all(plugin in plugins for plugin in fragment.when_plugins)


def compose(
    *,
    identity: Mapping[str, str],
    identity_text: str = "",
    fragments: Sequence[tuple[str, FragmentRecord]],
    tools: Sequence[str],
    plugins: Sequence[str],
    generators: Mapping[str, Callable[[], str]] | None = None,
    environ: Mapping[str, str] | None = None,
) -> ComposedPrompt:
    """Compose the prompt. ``fragments`` are ``(plugin id, fragment)`` in resolution order."""

    generators = dict(generators or {})
    warnings: list[str] = []
    name = identity.get("name") or identity.get("id") or "an agent"
    role = identity.get("role") or ""
    head = identity_text.strip() or (f"You are {name}, {role}." if role else f"You are {name}.")
    composed: list[ComposedFragment] = [
        ComposedFragment(
            id=f"{identity.get('id', 'agent')}.identity",
            plugin=f"agent:{identity.get('id', '')}",
            section="identity",
            text=render_template(head, identity=identity, environ=environ),
            tokens=(len(head) + 3) // 4,
        )
    ]
    by_section: dict[str, list[ComposedFragment]] = {section: [] for section in SECTIONS}
    for plugin, fragment in fragments:
        if not fragment_applies(fragment, tools, plugins):
            continue
        text = render_template(fragment.body, identity=identity, environ=environ)
        if fragment.generate:
            generator = generators.get(fragment.generate)
            generated = generator() if generator is not None else ""
            if generator is None:
                warnings.append(f"{fragment.id}: no generator for {fragment.generate!r}")
            text = "\n\n".join(part for part in (text, generated) if part)
        elif fragment.tokens > FRAGMENT_TOKEN_BUDGET:
            warnings.append(
                f"{fragment.id}: about {fragment.tokens} tokens, above the "
                f"{FRAGMENT_TOKEN_BUDGET}-token fragment budget"
            )
        by_section[fragment.section].append(
            ComposedFragment(
                id=fragment.id,
                plugin=plugin,
                section=fragment.section,
                text=text,
                tokens=(len(text) + 3) // 4,
                path=fragment.path,
            )
        )
    for section in SECTIONS[1:]:
        composed.extend(by_section[section])
    return ComposedPrompt(fragments=tuple(composed), warnings=tuple(warnings))
