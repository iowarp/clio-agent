import {sendCommand as command} from './capture-client.mjs';
import puppeteer from 'puppeteer';
import {readFile} from 'node:fs/promises';
const name=process.argv[2];
if(!name) throw new Error('Supply a unique take name');
let state=await command({op:'inspect'});
const exit=state.controls.find(c=>c.aria==='Exit full screen');
if(exit) await command({op:'click',x:exit.rect.x+exit.rect.w/2,y:exit.rect.y+exit.rect.h/2});
await command({op:'move',from:[1562,34],to:[1249,1015],ms:250});
await command({op:'wait',ms:500});
await command({op:'start',name});
await command({op:'mark',label:'inline-figure'});
await command({op:'wait',ms:1600});
const [port,path]=(await readFile('.capture-profile/DevToolsActivePort','utf8')).trim().split(/\r?\n/);
const browser=await puppeteer.connect({browserWSEndpoint:`ws://127.0.0.1:${port}${path}`,defaultViewport:null});
const page=(await browser.pages()).find(p=>p.url().includes(':5176/'));
const rect=await page.$$eval('[data-slot="a2ui-media-image"] button[aria-label="Full screen"]',buttons=>buttons.map(b=>b.getBoundingClientRect().toJSON()).filter(r=>r.width && r.y>=0 && r.y<innerHeight).at(-1));
await browser.disconnect();
if(!rect) throw new Error('Visible Image fullscreen button missing; retain recording');
const point=[rect.x+rect.width/2,rect.y+rect.height/2];
await command({op:'move',from:[1249,1015],to:point,ms:260});
await command({op:'click',x:point[0],y:point[1]});
await command({op:'mark',label:'image-expanded'});
await command({op:'move',from:point,to:[1420,980],ms:300});
await command({op:'wait',ms:4800});
await command({op:'shot',name:name+'-full-image'});
console.log(JSON.stringify(await command({op:'stop'})));
