#!/usr/bin/env bash
# The CLIO Desktop package for Arch Linux (pacman), made from the bundled deb.
#
#   arch-package.sh DEB VERSION ARCH OUT
#
# DEB is the bundled deb clio-bundles.yml just built, VERSION the release version
# (0.9.6.1, 0.9.7-beta.1), ARCH x86_64 or aarch64 and OUT the .pkg.tar.zst to write.
#
# The package carries the deb's files unchanged: the desktop, the runtime archive and its
# unpacker. Its install hooks are the deb's and rpm's maintainer scripts, embedded
# verbatim, so the three formats unpack and remove the runtime the same way. WebKitGTK
# 4.1 and the rest come from Arch's own repositories, as they come from apt and dnf.
# Needs bsdtar (libarchive) and zstd.
set -euo pipefail

[ "$#" = 4 ] || { echo "usage: $0 DEB VERSION ARCH OUT" >&2; exit 2; }
deb="$(cd "$(dirname "$1")" && pwd)/$(basename "$1")"
version="$2" arch="$3" out="$4"
case "$out" in /*) ;; *) out="$PWD/$out" ;; esac
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
case "$arch" in x86_64|aarch64) ;; *) echo "unsupported arch: $arch" >&2; exit 2 ;; esac
for tool in bsdtar zstd; do
  command -v "$tool" >/dev/null || { echo "$tool is required" >&2; exit 1; }
done

# pacman versions may not contain a hyphen. Dropping it keeps the order: vercmp ranks a
# letter run below a number, so 0.9.7beta.1 < 0.9.7 < 0.9.7.1.
pkgver="${version//-/}"
[[ "$pkgver" =~ ^[0-9][0-9A-Za-z.]*$ ]] || { echo "invalid version: $version" >&2; exit 2; }

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
mkdir "$work/root"
bsdtar -xf "$deb" -C "$work" 'data.tar.*'
bsdtar -xpf "$work"/data.tar.* -C "$work/root"
rm -f "$work"/data.tar.*
[ -f "$work/root/usr/lib/CLIO Desktop/gact-runtime.pack.json" ] \
  || { echo "$deb is not a bundled CLIO Desktop package" >&2; exit 1; }

# pacman runs these with /bin/sh in the installed system. Each embeds a maintainer
# script and passes the argument the deb gives it for the same event.
hook() {  # FUNCTION SCRIPT ARGUMENT
  printf '%s() {\n  sh -s -- %s <<'"'"'CLIO_SCRIPT'"'"'\n' "$1" "$3"
  cat "$here/$2"
  printf 'CLIO_SCRIPT\n}\n\n'
}
{
  printf '# CLIO Desktop: the deb and rpm maintainer scripts (install/linux-package), verbatim.\n\n'
  hook post_install postinst configure
  printf 'post_upgrade() {\n  post_install\n}\n\n'
  hook pre_remove prerm remove
  hook post_remove postrm remove
} > "$work/root/.INSTALL"

size="$(du -sb --exclude=.INSTALL "$work/root" | cut -f1)"
cat > "$work/root/.PKGINFO" <<EOF
# Generated by install/linux-package/arch-package.sh
pkgname = clio-desktop
pkgbase = clio-desktop
pkgver = $pkgver-1
pkgdesc = CLIO Desktop: the scientific agent interface, with its agent runtime
url = https://github.com/iowarp/clio-agent
builddate = $(date +%s)
packager = IOWarp
size = $size
arch = $arch
license = BSD-3-Clause
depend = webkit2gtk-4.1
depend = gtk3
depend = libayatana-appindicator
depend = zstd
EOF

cd "$work/root"
# Every file the package installs, with its checksum, as makepkg writes it. Owners are
# left out: whoever runs this, the files belong to root once installed.
LANG=C bsdtar -czf .MTREE --format=mtree \
  --options='!all,use-set,type,mode,time,size,sha256,link' \
  .PKGINFO .INSTALL usr
# The runtime archive is already zstd-19: level 1 only frames it.
LANG=C bsdtar -cf - --uid 0 --gid 0 --uname root --gname root .MTREE .PKGINFO .INSTALL usr | zstd -1 -q -T0 -f -o "$out"
echo "wrote $out ($(du -h "$out" | cut -f1))"
